-- Fresh database. Hibernate only checks these tables; Flyway creates them.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    password character varying(128) NOT NULL,
    last_login timestamp with time zone,
    is_superuser boolean NOT NULL,
    username character varying(150) NOT NULL,
    first_name character varying(150) NOT NULL,
    last_name character varying(150) NOT NULL,
    email character varying(254) NOT NULL,
    is_staff boolean NOT NULL,
    is_active boolean NOT NULL,
    date_joined timestamp with time zone NOT NULL,
    name character varying(100) NOT NULL,
    mob character varying(15) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_mob_key UNIQUE (mob)
);

CREATE TABLE otp_codes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    channel character varying(10) NOT NULL,
    value character varying(100) NOT NULL,
    code_hash character varying(128) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    attempts integer NOT NULL,
    is_used boolean NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT otp_codes_pkey PRIMARY KEY (id)
);

CREATE TABLE images (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    image character varying(100) NOT NULL,
    uploaded_at timestamp with time zone NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT images_pkey PRIMARY KEY (id),
    CONSTRAINT images_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX images_user_id_idx ON images (user_id);
